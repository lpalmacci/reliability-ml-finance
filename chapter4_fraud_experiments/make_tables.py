"""Step 7: the tables of Chapter 4 and of its Appendix, from results/chapter4_results.json.

    python make_tables.py    ->  results/tables/*.tex

| File | Table of the thesis |
|---|---|
| data_table.tex           | the two datasets and their partitions (Data and partitions) |
| members_table.tex        | members and ensembles on the test cases (Members and ensembles) |
| main_table.tex           | errors captured on the two datasets, K = 3, 12, 36 (The signal against the simpler readings) |
| main_table_all_K.tex     | the same for every K (Appendix, Complete results) |
| budgets_table.tex        | half and twice the budget (Appendix) |
| verdict_table.tex        | the verdict at its own budget (Appendix) |
| shares_table.tex         | fixed shares of the cases (Appendix) |
| ablations_table.tex      | variants of the procedure (Appendix) |
| gate_table.tex           | the admissibility gate against the allocated reading (Appendix) |

The files contain the tabular environments as they appear in the thesis. Do not edit them by hand.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
KS = (3, 6, 12, 24, 36)
DATASETS = (("carclaims", "carclaims"), ("ulb", "ULB"))
TAU = {("carclaims", "tau_F1"): r"$\tau_{F_1}$", ("carclaims", "tau_cost"): r"$0.1$",
       ("ulb", "tau_F1"): r"$\tau_{F_1}$", ("ulb", "tau_cost"): r"$1/101$"}
STRATEGIES = (("s1", "S1"), ("s2", "S2"))
THRESHOLDS = ("tau_F1", "tau_cost")


def index(rows, *extra):
    return {tuple(r[k] for k in ("dataset", "strategy", "threshold", "K", "budget") + extra): r for r in rows}


def pct(x):
    return f"{100 * x:.1f}"


def diff(r):
    """Mean difference in points, with the partitions above / below zero in superscript."""
    m = 100 * r["mean"]
    s = "+0.0" if abs(m) < 0.05 else f"{m:+.1f}"
    return f"${s}^{{{r['above_zero']}/{r['below_zero']}}}$"


def head(lines, cols, header):
    lines += ["% generated by make_tables.py: do not edit by hand", "\\begin{tabular}{" + cols + "}", "\\toprule",
              header + " \\\\", "\\midrule"]


def main_table(P, A, C, ks):
    L = []
    head(L, "llllrrrrrrr",
         r"& & & & \multicolumn{3}{c}{Errors captured (\%)} & \multicolumn{4}{c}{Signal minus reference (points)} \\"
         "\n" r"\cmidrule(lr){5-7}\cmidrule(lr){8-11}" "\n"
         r"Data & $\tau$ & & $K$ & random & signal & simple & simple & allocated & $\hat y=1$ & $\hat y=0$")
    first = True
    for ds, dname in DATASETS:
        for thr in THRESHOLDS:
            if not first:
                L.append("\\addlinespace")
            first = False
            for i_s, (st, sname) in enumerate(STRATEGIES):
                for i_k, K in enumerate(ks):
                    k = (ds, st, thr, K, "rho=1")
                    p, a, c1, c0 = P[k], A[k], C[k + (1,)], C[k + (0,)]
                    lead = [dname if (i_s == 0 and i_k == 0 and thr == "tau_F1") else "",
                            TAU[(ds, thr)] if (i_s == 0 and i_k == 0) else "", sname if i_k == 0 else "", str(K)]
                    cells = [pct(p["random"]), pct(p["confidex"]), pct(p["choice_captured"]), diff(p), diff(a), diff(c1), diff(c0)]
                    L.append(" & ".join(lead + cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    return L


def ablations_table(AB):
    variants = (("lambda0 = 36", r"$\lambda_0=36$"), ("non-directional", "non-directional"), ("gate", "gate"),
                ("clip 1e-4", r"clip $10^{-4}$"), ("confidex plug-in", r"law at $\bar c$"))
    L = []
    head(L, "lll" + "r" * len(KS), r"Variant & & $\tau$ & " + " & ".join(f"$K={K}$" for K in KS))
    for i_d, (ds, dname) in enumerate(DATASETS):
        if i_d:
            L.append("\\addlinespace")
        L.append(f"\\multicolumn{{{3 + len(KS)}}}{{l}}{{\\emph{{{dname}}}}} \\\\")
        first = True
        for var, vname in variants:
            if (ds, STRATEGIES[0][0], "tau_F1", KS[0], "rho=1", var) not in AB:
                continue
            if not first:
                L.append("\\addlinespace[2pt]")
            first = False
            for i_s, (st, sname) in enumerate(STRATEGIES):
                for i_t, thr in enumerate(THRESHOLDS):
                    lead = [vname if (i_s == 0 and i_t == 0) else "", sname if i_t == 0 else "", TAU[(ds, thr)]]
                    L.append(" & ".join(lead + [diff(AB[(ds, st, thr, K, "rho=1", var)]) for K in KS]) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    return L


def gate_table(G):
    L = []
    head(L, "llrr" + "r" * len(KS), r"& $\tau$ & Positive & Set aside & " + " & ".join(f"$K={K}$" for K in KS))
    for i_d, (ds, dname) in enumerate(DATASETS):
        if i_d:
            L.append("\\addlinespace")
        L.append(f"\\multicolumn{{{4 + len(KS)}}}{{l}}{{\\emph{{{dname}}}}} \\\\")
        for st, sname in STRATEGIES:
            for i_t, thr in enumerate(THRESHOLDS):
                g = [G[(ds, st, thr, K, "rho=1")] for K in KS]
                qa = [x["share_abstained_positive"] for x in g]
                lead = [sname if i_t == 0 else "", TAU[(ds, thr)],
                        f"{100 * sum(x['share_positive'] for x in g) / len(g):.1f}\\%",
                        f"{100 * min(qa):.0f}--{100 * max(qa):.0f}\\%"]
                L.append(" & ".join(lead + [diff(x) for x in g]) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    return L


FAMILIES = (("LightGBM_constrained", "LightGBM"), ("LightGBM", "LightGBM"), ("XGBoost", "XGBoost"),
            ("CatBoost", "CatBoost"), ("RandomForest", "random forest"), ("ExtraTrees", "extra trees"),
            ("LogReg", "logistic regression"), ("MLP", "MLP"), ("SVM_RBF", "SVM (RBF)"), ("TabPFN", "TabPFN"))
DECIMALS = {"carclaims": 1, "ulb": 2}   # decimals of the Brier score (x 10^3) and of the share of positives


def mmm(r, c, dec, scale=1.0, centre="median"):
    v = [scale * r[f"{c}_{x}"] for x in (centre, "min", "max")]
    return f"{v[0]:.{dec}f} [{v[1]:.{dec}f}, {v[2]:.{dec}f}]"


def members_table(PM, PE):
    def ensemble_three(ds, st):
        """AUROC, AUPRC and Brier of the ensemble of 36 do not depend on the threshold."""
        a, b = PE[(ds, st, "tau_F1")], PE[(ds, st, "tau_cost")]
        assert all(a[f"{c}_{x}"] == b[f"{c}_{x}"] for c in ("AUROC", "AUPRC", "Brier") for x in ("mean", "min", "max"))
        return a

    L = []
    head(L, "llrrr", r"& Family & AUROC & AUPRC & Brier ($\times 10^{3}$)")
    for i_d, (ds, dname) in enumerate(DATASETS):
        if i_d:
            L.append("\\addlinespace")
        prev = next(r for k, r in PM.items() if k[0] == ds)["test_prevalence"]
        L.append(f"\\multicolumn{{5}}{{l}}{{\\emph{{{dname}}}, frauds {100 * prev:.{DECIMALS[ds]}f}\\% of the test cases}} \\\\")
        for st, sname in STRATEGIES:
            fams = [(f, n) for f, n in FAMILIES if (ds, st, f) in PM]
            for i_f, (f, fname) in enumerate(fams):
                r = PM[(ds, st, f)]
                cells = [mmm(r, "AUROC", 3), mmm(r, "AUPRC", 3), mmm(r, "Brier", DECIMALS[ds], 1e3)]
                L.append(" & ".join([sname if i_f == 0 else "", fname] + cells) + " \\\\")
            r = ensemble_three(ds, st)
            cells = [mmm(r, "AUROC", 3, centre="mean"), mmm(r, "AUPRC", 3, centre="mean"),
                     mmm(r, "Brier", DECIMALS[ds], 1e3, "mean")]
            L.append(" & ".join(["", "ensemble of 36"] + cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\par\\medskip", "\\begin{tabular}{llrrrrr}", "\\toprule",
          r"& $\tau$ & Precision (\%) & Recall (\%) & FP & FN & Positive (\%)" " \\\\", "\\midrule"]
    for i_d, (ds, dname) in enumerate(DATASETS):
        if i_d:
            L.append("\\addlinespace")
        L.append(f"\\multicolumn{{7}}{{l}}{{\\emph{{{dname}}}, ensembles of 36 members}} \\\\")
        for st, sname in STRATEGIES:
            for i_t, thr in enumerate(THRESHOLDS):
                r = PE[(ds, st, thr)]
                cells = [mmm(r, "precision", 0, 100, "mean"), mmm(r, "recall", 0, 100, "mean"),
                         mmm(r, "FP", 0, centre="mean"), mmm(r, "FN", 0, centre="mean"),
                         mmm(r, "share_positive", DECIMALS[ds], 100, "mean")]
                L.append(" & ".join([sname if i_t == 0 else "", TAU[(ds, thr)]] + cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    return L


def data_table(DATA):
    parts = (("train", "Training"), ("calibration", "Calibration"), ("validation", "Validation"), ("test", "Test"))

    def from_to(a, b):
        return f"{a:,}" if a == b else f"{a:,}--{b:,}"

    q = DATA["carclaims"]["parts"]
    assert all(DATA[d]["parts"][p]["share"] == q[p]["share"] for d in DATA for p, _ in parts)
    L = []
    head(L, "lrrrr", "& " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{dname}}}" for _, dname in DATASETS) + " \\\\\n"
         + "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(DATASETS))) + "\n"
         + "Part & " + " & ".join("cases & frauds" for _ in DATASETS))
    rows = [("All", [(f"{DATA[ds]['rows']:,}", f"{DATA[ds]['frauds']:,}") for ds, _ in DATASETS])]
    rows += [(f"{n} ({100 * q[p]['share']:.0f}\\%)",
              [tuple(from_to(DATA[ds]["parts"][p][f"{t}_min"], DATA[ds]["parts"][p][f"{t}_max"]) for t in ("rows", "frauds"))
               for ds, _ in DATASETS]) for p, n in parts]
    for name, cells in rows:
        L.append(" & ".join([name] + [x for c in cells for x in c]) + " \\\\")
    L.append("\\midrule")
    for name, field in (("Variables", "variables"), ("Partitions", "partitions")):
        L.append(" & ".join([name] + [f"\\multicolumn{{2}}{{c}}{{{DATA[ds][field]}}}" for ds, _ in DATASETS]) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    return L


def blocks(L, row, ncol):
    """A header row for each dataset, then threshold, construction and K."""
    for i_d, (ds, dname) in enumerate(DATASETS):
        if i_d:
            L.append("\\addlinespace")
        L.append(f"\\multicolumn{{{ncol}}}{{l}}{{\\emph{{{dname}}}}} \\\\")
        for i_t, thr in enumerate(THRESHOLDS):
            if i_t:
                L.append("\\addlinespace[2pt]")
            for i_s, (st, sname) in enumerate(STRATEGIES):
                for i_k, K in enumerate(KS):
                    lead = [TAU[(ds, thr)] if (i_s == 0 and i_k == 0) else "", sname if i_k == 0 else "", str(K)]
                    L.append(" & ".join(lead + row(ds, st, thr, K)) + " \\\\")


def main() -> None:
    R = json.loads((HERE / "results" / "chapter4_results.json").read_text())
    P, A = index(R["main"]), index(R["allocation"])
    C = index(R["within_class"], "class")
    AB = index(R["ablations"], "variant")
    G = index(R["gate_allocation"])
    PM = {(r["dataset"], r["strategy"], r["family"]): r for r in R["performance_members"]}
    PE = {(r["dataset"], r["strategy"], r["threshold"]): r for r in R["performance_ensemble"]}
    DATA = {r["dataset"]: r for r in R["data"]}

    def verdict_row(ds, st, thr, K):
        k = (ds, st, thr, K, "k_alpha")
        p, a, c1, c0 = P[k], A[k], C[k + (1,)], C[k + (0,)]
        return [f"{p['k']:.0f}", f"{P[(ds, st, thr, K, 'rho=1')]['k']:.0f}", f"{100 * p['share_budget_positive']:.0f}",
                pct(p["confidex"]), diff(p), diff(a), diff(c1), diff(c0)]

    def budget_row(ds, st, thr, K):
        out = []
        for b in ("rho=0.5", "rho=2"):
            k = (ds, st, thr, K, b)
            out += [diff(P[k]), diff(A[k]), diff(C[k + (1,)]), diff(C[k + (0,)])]
        return out

    def shares_row(ds, st, thr, K):
        out = []
        for b in ("share=1%", "share=5%", "share=10%"):
            p = P[(ds, st, thr, K, b)]
            out += [pct(p["confidex"]), pct(p["perfect"]), diff(p)]
        return out

    verdict, budgets_, shares = [], [], []
    head(verdict, "lllrrrrrrrr",
         r"& & & & & & & \multicolumn{4}{c}{Signal minus reference (points)} \\" "\n" r"\cmidrule(lr){8-11}" "\n"
         r"$\tau$ & & $K$ & $k_\alpha$ & $k_{\rho=1}$ & positive (\%) & signal (\%) & simple & allocated & $\hat y=1$ & $\hat y=0$")
    blocks(verdict, verdict_row, 11)
    verdict += ["\\bottomrule", "\\end{tabular}"]
    head(budgets_, "lllrrrrrrrr",
         r"& & & \multicolumn{4}{c}{$\rho=0.5$} & \multicolumn{4}{c}{$\rho=2$} \\" "\n"
         r"\cmidrule(lr){4-7}\cmidrule(lr){8-11}" "\n"
         r"$\tau$ & & $K$ & simple & alloc. & $\hat y=1$ & $\hat y=0$ & simple & alloc. & $\hat y=1$ & $\hat y=0$")
    blocks(budgets_, budget_row, 11)
    budgets_ += ["\\bottomrule", "\\end{tabular}"]
    head(shares, "lllrrrrrrrrr",
         r"& & & \multicolumn{3}{c}{1\% of the cases} & \multicolumn{3}{c}{5\% of the cases} & \multicolumn{3}{c}{10\% of the cases} \\"
         "\n" r"\cmidrule(lr){4-6}\cmidrule(lr){7-9}\cmidrule(lr){10-12}" "\n"
         r"$\tau$ & & $K$ & signal & perfect & diff. & signal & perfect & diff. & signal & perfect & diff.")
    blocks(shares, shares_row, 12)
    shares += ["\\bottomrule", "\\end{tabular}"]

    out = HERE / "results" / "tables"
    out.mkdir(parents=True, exist_ok=True)
    files = {"main_table.tex": main_table(P, A, C, (3, 12, 36)), "main_table_all_K.tex": main_table(P, A, C, KS),
             "ablations_table.tex": ablations_table(AB), "gate_table.tex": gate_table(G),
             "members_table.tex": members_table(PM, PE), "data_table.tex": data_table(DATA),
             "verdict_table.tex": verdict, "budgets_table.tex": budgets_, "shares_table.tex": shares}
    for name, lines in files.items():
        (out / name).write_text("\n".join(lines) + "\n")
    print("written:", ", ".join(files), "in", out)


if __name__ == "__main__":
    main()
