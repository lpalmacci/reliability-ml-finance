"""The two tables of the Appendix of Chapter 3, from the saved results.

    python make_tables.py    ->  results/tables/settings_table.tex   (Table A.1, settings of every experiment)
                                 results/tables/budget_table.tex     (Table A.2, errors captured at three budgets)

The files contain the tabular environments as they appear in the thesis. Do not edit them by hand.
"""
import json
from pathlib import Path

from synthetic import DESIGNS, SIMPLE_READINGS

HERE = Path(__file__).resolve().parent
KS = (3, 6, 12, 24, 36)
fmt = lambda x: "+0.0" if abs(x) < 0.05 else f"{x:+.1f}"

# Table A.1: settings of the experiments. "Notebook" is the section of replicate_chapter3.ipynb.
GRID = "3--36"
SETTINGS = [
    ("Model densities", r"\labelcref{sec:conf-model,sec:conf-relative}", "--", "--", "--", "analytical", "2"),
    ("Inferred location", r"\labelcref{sec:conf-specs}", "5", "1", "--", "constructed", "6.1"),
    ("Grid against quadrature", r"\labelcref{sec:conf-inference}", "3, 6, 12", "40", "--", "Beta model", "1.1, 6.6"),
    ("Ties and near-ties", r"\labelcref{sec:conf-inference}", "3, 12, 36", "1", "--", "constructed", "6.6"),
    ("Relative measure", r"\labelcref{sec:conf-relative}", "27", "1", "--", "constructed", "6.3"),
    ("Shrinkage", r"\labelcref{sec:conf-law}", GRID, "2000", "0.5", "mixed", "6.2"),
    ("Gate correlation", r"\labelcref{sec:conf-signal}", GRID, "5000", "0.5", "mixed", "6.5"),
    ("Sensitivity", r"\labelcref{sec:conf-sensitivity}", GRID, r"2000\textsuperscript{a}", "0.25, 0.5", "mixed", "5"),
    ("Ten ensembles", r"\labelcref{sec:conf-illustration}", "10", "10", "0.1, 0.5", "constructed", "3"),
    ("Known truth, AUROC", r"\labelcref{sec:conf-validation}", GRID, "20\\,000", "0.1, 0.5", "all three", "4.1--4.4"),
    ("Known truth, budget", r"\labelcref{sec:conf-validation}", GRID, "20\\,000", "0.1, 0.5", "all three", "4.5"),
    ("Anchoring near zero", r"\labelcref{sec:conf-limits}", "3", "2000", "--", "log-normal", "6.4"),
]


def settings_table() -> str:
    lines = ["% generated by make_tables.py: do not edit by hand",
             "\\begin{tabular}{@{}lllllll@{}}", "\\toprule",
             "Experiment & Section & $K$ & Cases & $\\tau$ & Design & Notebook \\\\", "\\midrule"]
    lines += [" & ".join(r) + " \\\\" for r in SETTINGS]
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def budget_table(budget: dict) -> str:
    """Signal minus the best of the four simpler readings at the same budget, in percentage points; the
    asterisk marks the 10% differences whose 95% bootstrap interval excludes zero."""
    lines = ["% generated by make_tables.py: do not edit by hand",
             "\\begin{tabular}{llr" + "r" * len(KS) + "}", "\\toprule",
             "Design & $\\tau$ & Budget & " + " & ".join(f"$K={K}$" for K in KS) + " \\\\", "\\midrule"]
    for d in DESIGNS:
        for tau in ("0.5", "0.1"):
            for i, b in enumerate(("0.05", "0.1", "0.2")):
                cells = []
                for K in KS:
                    g = budget[f"{d}|{tau}|{K}"]
                    x = 100 * (g[f"confidex@{b}"] - max(g[f"{m}@{b}"] for m in SIMPLE_READINGS))
                    star = "^{\\ast}" if b == "0.1" and not (g["lo@0.1"] <= 0 <= g["hi@0.1"]) else ""
                    cells.append(f"${fmt(x)}{star}$")
                lead = (d if (tau == "0.5" and i == 0) else "") + " & " + (f"${tau}$" if i == 0 else "")
                lines.append(f"{lead} & {int(round(100 * float(b)))}\\% & " + " & ".join(cells) + " \\\\")
            if not (d == "mixed" and tau == "0.1"):
                lines.append("\\addlinespace")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    R = json.loads((HERE / "results" / "chapter3_results.json").read_text())
    out = HERE / "results" / "tables"
    out.mkdir(parents=True, exist_ok=True)
    (out / "settings_table.tex").write_text(settings_table())
    (out / "budget_table.tex").write_text(budget_table(R["budget"]))
    print("written:", out / "settings_table.tex", out / "budget_table.tex")
