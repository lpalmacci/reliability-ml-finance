"""E10, step 1 (additional analysis on market data, not pre-registered; deviation D8): pseudo-real oracles.

A GJR-GARCH(1,1)-t and a two-state Markov-switching log-normal model are estimated by maximum
likelihood on the daily log-returns of the US market, 1926-2026 (`tavp.market`). The estimates
define the two processes of `configs/real.yaml`, on which the protocol is then applied unchanged
(`make real`). The file is generated here and must not be edited by hand.
"""

from __future__ import annotations

import json
import math

import numpy as np
import pandas as pd

from tavp.experiments import common
from tavp.market import VINTAGE_LAST_DATE, VINTAGE_SHA256, market_log_returns
from tavp.utils import REPO_ROOT

DAYS = 252


def fit_gjr(r: np.ndarray) -> dict:
    """GJR-GARCH(1,1)-t with the drift set to the sample mean and the other parameters estimated by ML.

    The location estimated by ML under the symmetric Student-t likelihood is far above the sample
    mean of the log-returns, which are negatively skewed (the likelihood down-weights large moves),
    so an oracle with that drift would not reproduce the average return of the market; it is
    recorded as `_mu_ann_ml` and reported (deviation D8).
    """
    from arch import arch_model

    ml = arch_model(100.0 * r, mean="Constant", vol="GARCH", p=1, o=1, q=1, dist="t").fit(disp="off")
    res = arch_model(100.0 * (r - r.mean()), mean="Zero", vol="GARCH", p=1, o=1, q=1, dist="t").fit(disp="off")
    p, se = res.params, res.std_err
    alpha, gamma, beta = float(p["alpha[1]"]), float(p["gamma[1]"]), float(p["beta[1]"])
    pers = alpha + 0.5 * gamma + beta
    return {"mu_ann": float(r.mean()) * DAYS, "_mu_ann_ml": float(ml.params["mu"]) / 100.0 * DAYS,
            "vol_ann": math.sqrt(float(p["omega"]) / 1e4 / (1.0 - pers) * DAYS),
            "alpha": alpha, "gamma": gamma, "beta": beta, "nu": float(p["nu"]), "burn": 500,
            "_persistence": pers, "_loglik": float(res.loglikelihood),
            "_se": {k: float(v) for k, v in se.items()}}


def fit_regime(r: np.ndarray) -> dict:
    from statsmodels.tsa.regime_switching.markov_regression import MarkovRegression

    # deterministic starts (statsmodels' random search is not seedable): the default start and a
    # grid of calm/turbulent starting values; the fit with the largest likelihood is kept
    model = MarkovRegression(100.0 * r, k_regimes=2, trend="c", switching_variance=True)
    starts = [None] + [np.array([p00, 1.0 - p11, 0.08, -0.10, 0.4, v2])
                       for p00 in (0.98, 0.995) for p11 in (0.95, 0.98) for v2 in (2.0, 5.0)]
    fits = [model.fit(start_params=st, disp=False, maxiter=500) for st in starts]
    res = max(fits, key=lambda f: f.llf)
    p = pd.Series(res.params, index=res.model.param_names)
    c = np.array([p["const[0]"], p["const[1]"]]) / 100.0
    s2 = np.array([p["sigma2[0]"], p["sigma2[1]"]]) / 1e4
    stay = np.array([p["p[0->0]"], 1.0 - p["p[1->0]"]])
    bull, bear = (0, 1) if s2[0] <= s2[1] else (1, 0)  # state 1 of the model is the calm one
    sig = np.sqrt(s2 * DAYS)
    mu = c * DAYS + 0.5 * sig**2  # r | s ~ N((mu - sigma^2 / 2) dt, sigma^2 dt)
    return {"p11": float(stay[bull]), "p22": float(stay[bear]), "mu1": float(mu[bull]), "sigma1": float(sig[bull]),
            "mu2": float(mu[bear]), "sigma2": float(sig[bear]), "_loglik": float(res.llf)}


def _clean(d: dict) -> dict:
    return {k: (round(v, 6) if isinstance(v, float) else v) for k, v in d.items() if not k.startswith("_")}


def main():
    args = common.parse_args(__doc__)
    base = common.load(args.config)
    d, r = market_log_returns()
    gjr = fit_gjr(r)
    reg = fit_regime(r)
    dgps = {"gjr_real": {"name": "gjr_garch_t", **_clean(gjr)}, "regime_real": {"name": "regime", **_clean(reg)}}
    lines = ["# Market-data study (deviation D8, not pre-registered).",
             "# GENERATED by `python -m tavp.experiments.e10_calibrate`: do not edit by hand.",
             f"# Processes estimated on the daily US market log-returns {d[0]}-{d[-1]} ({len(r)} days),",
             f"# Ken French Data Library, CRSP vintage ending {VINTAGE_LAST_DATE} (zip sha256 {VINTAGE_SHA256[:12]}...).",
             "extends: full.yaml", "replace: [dgps]", "runtime:", "  results_suffix: real",
             "  train_generators: [tcvae]", "generators:", "  scaling_rule: {inherit: results/train/scaling_decision.json}",
             "  vae_mlp: {seeds: 0}", "dgps:"]
    for k, v in dgps.items():
        lines.append(f"  {k}: {{" + ", ".join(f"{a}: {b}" for a, b in v.items()) + "}")
    (REPO_ROOT / "configs" / "real.yaml").write_text("\n".join(lines) + "\n")
    cfg = common.load("configs/real.yaml")
    rows = [{"model": "gjr_garch_t", **{k: v for k, v in gjr.items() if k != "_se"}},
            {"model": "regime", **reg}]
    common.save_table(pd.DataFrame(rows), "e10", "calibration", cfg)
    summary = {"days": int(len(r)), "first": int(d[0]), "last": int(d[-1]), "mean_ann": float(r.mean() * DAYS),
               "vol_ann": float(r.std() * math.sqrt(DAYS)), "gjr_se": gjr["_se"]}
    (common.results_root(cfg) / "e10" / "sample.json").write_text(json.dumps(summary, indent=2))
    print(json.dumps(dgps, indent=2))


if __name__ == "__main__":
    main()
