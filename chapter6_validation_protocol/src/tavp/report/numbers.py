"""Numbers quoted in the chapter, written as LaTeX macros so that no number is typed by hand.

In the chapter, \\tavp{key} expands to the value stored under `key`; an undefined key prints
a red marker instead of failing silently.
"""

from __future__ import annotations

import json
from pathlib import Path

HEADER = r"""% Generated by tavp.report (make thesis). Do not edit by hand.
\providecommand{\tavp}[1]{\ifcsname tavp:#1\endcsname\csname tavp:#1\endcsname\else\textcolor{red}{[\detokenize{#1}]}\fi}
"""


class Numbers:
    def __init__(self):
        self.values: dict[str, str] = {}

    def add(self, key: str, value, fmt: str = "{:.2f}") -> None:
        if isinstance(value, str):
            self.values[key] = value
        elif isinstance(value, bool):
            self.values[key] = "yes" if value else "no"
        elif isinstance(value, int):
            self.values[key] = f"{value:,}".replace(",", "{,}")
        else:
            self.values[key] = fmt.format(value)

    def pct(self, key: str, share: float, digits: int = 0) -> None:
        self.values[key] = f"{100 * share:.{digits}f}\\%"

    def write(self, tex_path: Path, json_path: Path) -> None:
        lines = [HEADER] + [r"\expandafter\def\csname tavp:" + k + r"\endcsname{" + v + "}"
                            for k, v in sorted(self.values.items())]
        tex_path.parent.mkdir(parents=True, exist_ok=True)
        tex_path.write_text("\n".join(lines) + "\n")
        json_path.write_text(json.dumps(self.values, indent=2, sort_keys=True))
